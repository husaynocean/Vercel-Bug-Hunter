"""Draft contest-format write-ups for CONFIRMED findings only.
Output is a draft for human review; nothing is ever submitted automatically."""
from __future__ import annotations

import json
import re
from pathlib import Path

from bughunter import prove
from bughunter.contest import Contest

ASSESSED_TYPE = {
    "access-control": "Access Control", "reentrancy": "Reentrancy",
    "rounding-precision": "Math", "oracle-manipulation": "Oracle", "accounting": "Math",
    "external-integration": "Token-Transfer", "dos": "DoS", "standards-compliance": "ERC4626",
}


def _links(contest: Contest, funcs: list[dict], names: list[str]) -> list[str]:
    base = contest.repo.removesuffix(".git") + f"/blob/{contest.commit}/"
    prefix = "" if contest.scope.project_dir in (".", "") else contest.scope.project_dir + "/"
    out = []
    for n in names:
        fn = re.split(r"[.(]", n.split("(")[0])[-1]
        contract = n.split(".")[0] if "." in n else None
        for f in funcs:
            if f["function"] == fn and (contract is None or f["contract"] == contract):
                out.append(f"{base}{prefix}{f['file']}#L{f['lines'][0]}-L{f['lines'][1]}")
                break
    return sorted(set(out))


def draft(contest: Contest, workdir: Path) -> Path:
    funcs = json.loads((workdir / contest.id / "scan" / "functions.json").read_text())
    pdir = workdir / contest.id / "prove"
    out = workdir / contest.id / "report"
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.md"):
        old.unlink()
    items = prove.confirmed(workdir, contest)
    for c in items:
        test = (pdir / "pocs" / f"{c['cid']}.t.sol").read_text()
        patch = (pdir / "pocs" / f"{c['cid']}.patch").read_text()
        steps = "\n".join(f"{i}. {s}" for i, s in enumerate(c["attack_path"], 1))
        links = _links(contest, funcs, c["functions"] or [c["reviewed_function"]])
        md = f"""<!-- DRAFT generated by bughunter. Review and edit before submitting. -->
# {c['title']}

**Severity (proposed):** {c['severity'].capitalize()}

## Lines of code

{chr(10).join(links) or '(fill in)'}

## Vulnerability details

{c['root_cause']}

**Preconditions:** {c['preconditions']}

## Impact

{c['impact']}

## Proof of Concept

{steps}

Foundry test (place in `test/bughunter/{c['cid']}.t.sol` and run
`forge test --match-path test/bughunter/{c['cid']}.t.sol -vvv`):

```solidity
{test.rstrip()}
```

The test passes on the audited commit and fails once the mitigation below is applied.

## Tools Used

Manual review, Foundry

## Recommended Mitigation Steps

```diff
{patch.rstrip()}
```

## Assessed type

{ASSESSED_TYPE.get(c['category'], 'Other')}
"""
        slug = re.sub(r"[^a-z0-9]+", "-", c["title"].lower()).strip("-")[:60]
        (out / f"{c['severity'][0].upper()}-{c['cid']}-{slug}.md").write_text(md)
    return out
